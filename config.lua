-- config.lua
-- Общий конфиг для банк-сервера и всех станций.
-- ВАЖНО: этот файл должен быть ОДИНАКОВЫМ на банк-сервере и на каждой станции.

local config = {}

-- Порт modem, на котором "разговаривают" банк-сервер и станции.
-- Если у вас в сети есть другие моды/скрипты, использующие сеть - смените порт.
config.NET_PORT = 4422

-- Через сколько секунд станция считает, что банк не ответил, и повторяет запрос.
config.NET_TIMEOUT = 3
config.NET_RETRIES = 3

-- ===== Кошелёк 1: "Фишки" (за ресурсы) =====
-- Список ресурсов, которые принимает касса, и курс: сколько фишек за 1 единицу ресурса.
-- itemName - строго технической имя предмета Minecraft (mod:item или mod:item:meta,
-- смотрите через probe.lua / OpenPeripheral / NEI-аналог). label - просто для вывода на экран.
config.RESOURCES = {
    { itemName = "minecraft:iron_ingot",   label = "Железный слиток", rate = 1 },   -- 1 слиток = 1 фишка
    { itemName = "minecraft:gold_ingot",   label = "Золотой слиток",  rate = 3 },   -- 1 слиток = 3 фишки
    { itemName = "minecraft:diamond",      label = "Алмаз",           rate = 10 },  -- 1 алмаз = 10 фишек
}

-- ===== Кошелёк 2: "Кредиты" (валюта сервера) =====
-- Валюта сервера у вас реализована как обычный предмет - укажите его технич. имя.
config.SERVER_CURRENCY = {
    itemName = "minecraft:emerald", -- ЗАМЕНИТЕ на реальный предмет-валюту вашего сервера
    label    = "Кредит",
    rate     = 1, -- 1 предмет = 1 кредит (обычно 1:1 для валюты сервера)
}

-- Лимиты ставок в мини-играх (в единицах соответствующего кошелька: фишки или кредиты)
config.MIN_BET = 1
config.MAX_BET = 500

-- Названия кошельков для интерфейса
config.WALLETS = {
    chips   = { key = "chips",   label = "Фишки (ресурсы)" },
    credits = { key = "credits", label = "Кредиты (валюта сервера)" },
}

return config
